"""Certify two-ply legal trees and a synthetic nonterminal leaf contract.

This tests PVS plumbing independently of Maxima's evaluator and quiescence.
Extensions stop at the explicit two-ply contract; selective pruning is disabled.
"""
import argparse
from pathlib import Path
import zlib
import chess


def generate():
    positions = [chess.STARTING_FEN,
                 "7k/8/6p1/5n2/2N5/1P6/8/K7 w - - 0 1",
                 "7k/8/8/8/8/8/P7/KR6 w - - 0 1",
                 "7k/6Q1/8/8/8/8/8/K7 b - - 0 1",
                 "7k/5K2/6Q1/8/8/8/8/8 w - - 0 1"]
    nodes = {}

    def visit(board, ply):
        fen = board.fen(en_passant="fen")
        legal = sorted(board.legal_moves, key=lambda m: m.uci())
        if not legal:
            value = -30000 + ply if board.is_check() else 0
        elif board.is_insufficient_material() or board.halfmove_clock >= 100:
            value = 0
        elif ply == 2:
            # Deliberately arbitrary, stable scores: no engine evaluation labels.
            value = zlib.crc32(fen.encode("ascii")) % 801 - 400
        else:
            scores = []
            for move in legal:
                board.push(move)
                scores.append(-visit(board, ply + 1))
                board.pop()
            value = max(scores)
        row = (ply, value, " ".join(m.uci() for m in legal))
        assert nodes.setdefault(fen, row) == row
        return value

    for fen in positions:
        for board in (chess.Board(fen), chess.Board(fen).mirror()):
            assert board.is_valid(), board.fen()
            visit(board, 0)
    lines = ["// Generated by generate_tree.py using python-chess."]
    for fen, (ply, value, legal) in sorted(nodes.items()):
        lines.append('{"%s", %d, %d, "%s"},' % (fen, ply, value, legal))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).with_name("tree.inc")
    data = generate()
    if args.check:
        if path.read_text() != data:
            raise SystemExit("tree certificates differ; regenerate and review")
    else:
        path.write_text(data)
