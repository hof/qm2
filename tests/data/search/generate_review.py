"""Certify castling quiescence move sets and clock-100 terminal children."""
import argparse
from pathlib import Path
import chess


def render():
    roots = [
        'r3k3/8/8/8/8/8/8/4K2R w Kq - 99 1',
        '5k2/8/8/8/8/8/8/4K2R w K - 99 1',
        '4k3/8/8/8/8/8/8/R3K3 w Q - 99 1',
        '4k2r/8/8/8/8/8/8/4KR2 w k - 99 1',
        '3k4/8/8/8/8/8/8/R3K3 w Q - 99 1',
        'k4r2/8/8/8/8/8/8/4K2R w K - 99 1',
        'k3r3/8/8/8/8/8/8/4K2R w K - 99 1',
        '4k3/8/8/8/8/8/8/R3K2R w KQ - 99 1',
    ]
    rows = []
    for fen in roots:
        for board in (chess.Board(fen), chess.Board(fen).mirror()):
            assert board.is_valid()
            legal = sorted(board.legal_moves, key=lambda m: m.uci())
            entry, tactical, castles = [], [], []
            for move in legal:
                capture = board.is_capture(move)
                castle = board.is_castling(move)
                check = board.gives_check(move)
                if castle:
                    castles.append(move.uci())
                # These fixtures have no captures or promotions: every child
                # is independently a fifty-move draw, with no checkmate.
                assert not capture and not move.promotion
                if board.is_check() or castle or check:
                    entry.append(move.uci())
                if board.is_check() or castle:
                    tactical.append(move.uci())
                board.push(move)
                assert not board.is_checkmate() and board.halfmove_clock == 100
                assert board.is_fifty_moves() or board.is_stalemate()
                board.pop()
            rows.append('{"%s", "%s", "%s", "%s", "%s"},' % (
                board.fen(en_passant='fen'), ' '.join(m.uci() for m in legal),
                ' '.join(entry), ' '.join(tactical), ' '.join(castles)))
    return '// Generated by generate_review.py using python-chess.\n' + '\n'.join(rows) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).with_name('review.inc')
    output = render()
    if args.check:
        if path.read_text() != output:
            raise SystemExit('castling certificates differ')
    else:
        path.write_text(output)
