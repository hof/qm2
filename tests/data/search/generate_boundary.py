"""Regenerate terminal certificates with python-chess; native tests need no Python.

All legal children reach clock 100 without a capture or pawn move. Checkmate
precedes the engine's automatic fifty-move draw; no static evaluator is involved.
Run with --check to verify the committed certificates instead of rewriting them.
"""

import argparse
from pathlib import Path

import chess


def generate():
    positions = [
        "7k/5K2/6Q1/8/8/8/8/8 w - - 99 1",
        "7k/8/8/8/8/8/8/KR6 w - - 99 1",
        "R6k/8/5K2/8/8/8/8/8 b - - 99 1",
        "7k/5K2/6Q1/8/8/8/8/8 b - - 99 1",
        "7k/6Q1/5K2/8/8/8/8/8 b - - 99 1",
    ]
    lines = ["// Generated by generate_boundary.py using python-chess."]
    for fen in positions:
        for board in (chess.Board(fen), chess.Board(fen).mirror()):
            assert board.is_valid(), board.fen()
            legal = sorted(board.legal_moves, key=lambda move: move.uci())
            mates = []
            for move in legal:
                assert not board.is_zeroing(move), move
                board.push(move)
                assert board.halfmove_clock == 100
                if board.is_checkmate():
                    mates.append(move.uci())
                else:
                    assert board.is_stalemate() or board.is_fifty_moves()
                board.pop()
            expected = -30000 if board.is_checkmate() else 29999 if mates else 0
            lines.append('{"%s", %d, "%s", "%s"},' % (
                board.fen(), expected, " ".join(m.uci() for m in legal), " ".join(mates)))
    # The warm-parent regressions search these trees for two reversible plies.
    # Certify every leaf independently, including all possible king approaches.
    parent = chess.Board("7k/8/8/8/8/8/8/KR6 b - - 98 1")
    for board in (parent, parent.mirror()):
        assert board.is_valid()
        for first in list(board.legal_moves):
            assert not board.is_zeroing(first)
            board.push(first)
            for second in list(board.legal_moves):
                assert not board.is_zeroing(second)
                board.push(second)
                assert board.is_valid() and board.halfmove_clock == 100
                assert not board.is_checkmate() and board.is_fifty_moves()
                board.pop()
            board.pop()
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path(__file__).with_name("boundary.inc")
    data = generate()
    if args.check:
        if output.read_text() != data:
            raise SystemExit("boundary certificates differ; regenerate and review")
    else:
        output.write_text(data)
