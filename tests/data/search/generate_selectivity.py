"""Certify legal moves and tactical categories for selective guard probes."""
import argparse
from pathlib import Path
import chess


def generate():
    positions = [chess.STARTING_FEN,
                 "r3k2r/ppp2ppp/2n5/3pP3/8/2N5/PPP2PPP/R3K2R w KQkq d6 0 1",
                 "r3k2r/1P3ppp/8/8/8/8/PPP2PPP/R3K2R w KQkq - 0 1",
                 "r3k2r/5ppp/8/P7/8/8/1PP2PPP/R3K2R w KQkq - 0 1",
                 "r3k2r/ppp2ppp/8/8/8/8/PPP1rPPP/R3K2R w KQkq - 0 1",
                 "7k/7p/8/8/8/8/P7/KR6 w - - 0 1"]
    lines = ["// Generated by generate_selectivity.py using python-chess."]
    for fen in positions:
        for board in (chess.Board(fen), chess.Board(fen).mirror()):
            assert board.is_valid(), board.fen()
            moves = []
            for move in sorted(board.legal_moves, key=lambda m: m.uci()):
                capture = board.is_capture(move)
                castle = board.is_castling(move)
                advanced = False
                if board.piece_type_at(move.from_square) == chess.PAWN and not capture:
                    rank = chess.square_rank(move.to_square)
                    advanced = rank >= 5 if board.turn else rank <= 2
                    for pawn in board.pieces(chess.PAWN, not board.turn):
                        ahead = (chess.square_rank(pawn) > chess.square_rank(move.from_square)
                                 if board.turn else
                                 chess.square_rank(pawn) < chess.square_rank(move.from_square))
                        if ahead and abs(chess.square_file(pawn) - chess.square_file(move.from_square)) <= 1:
                            advanced = False
                flags = int(capture) | (2 if move.promotion else 0) | (4 if castle else 0)
                flags |= 8 if board.gives_check(move) else 0
                flags |= 16 if advanced else 0
                moves.append(f"{move.uci()}:{flags}")
            lines.append('{"%s", %s, "%s"},' % (
                board.fen(en_passant="fen"), str(board.is_check()).lower(), " ".join(moves)))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).with_name("selectivity.inc")
    data = generate()
    if args.check:
        if path.read_text() != data:
            raise SystemExit("selectivity certificates differ")
    else:
        path.write_text(data)
