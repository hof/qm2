"""Certify legal/tactical trees for real quiescence and one-ply PVS.

Terminal results and move sets come from python-chess. Native tests use Maxima
static evaluation as stand-pat labels, not as an independent evaluation oracle.
Checking PVS moves conservatively retain one ply, covering either SEE extension
choice; quiescence admits captures/promotions and all check evasions.
"""
import argparse
from pathlib import Path
import chess


def generate():
    positions = [
        "7k/8/8/3q4/8/8/8/K2R4 w - - 0 1",
        "3r3k/8/8/3q4/8/8/8/K2R4 w - - 0 1",
        "R6k/8/5K2/8/8/8/8/8 b - - 0 1",
        "7k/5K2/6q1/6Q1/8/8/8/8 w - - 0 1",
        "7k/8/5KQ1/8/8/8/8/8 w - - 0 1",
        "7k/P7/8/8/8/8/8/KR6 w - - 0 1",
        "7k/8/8/3pP3/8/8/8/KR6 w - d6 0 1",
    ]
    nodes, visited, roots = {}, set(), []

    def visit(board, mode, ply):
        assert ply < 12, (board.fen(), mode)
        fen = board.fen(en_passant="fen")
        key = (fen, mode)
        if key in visited:
            return
        visited.add(key)
        legal = sorted(board.legal_moves, key=lambda m: m.uci())
        check = board.is_check()
        terminal = -30000 if not legal and check else 0 if not legal or board.is_insufficient_material() or board.halfmove_clock >= 100 else 32002
        negative = [m for m in legal if check or board.is_capture(m) or m.promotion]
        entry = negative
        row = (check, terminal, " ".join(m.uci() for m in legal),
               " ".join(m.uci() for m in entry), " ".join(m.uci() for m in negative))
        assert nodes.setdefault(fen, row) == row
        if terminal != 32002:
            return
        for move in legal if mode == 1 else entry if mode == 0 else negative:
            checking = board.gives_check(move)
            board.push(move)
            visit(board, 1 if mode == 1 and checking else 0 if mode == 1 else -1, ply + 1)
            # A checking move with negative SEE is not extended by Maxima.
            if mode == 1 and checking:
                visit(board, 0, ply + 1)
            board.pop()

    for fen in positions:
        for board in (chess.Board(fen), chess.Board(fen).mirror()):
            assert board.is_valid(), board.fen()
            for clock in (0, 99):
                board.halfmove_clock = clock
                roots.append(board.fen(en_passant="fen"))
                for mode in (-1, 0, 1):
                    visit(board, mode, 0)
    history_lines = ["// Generated by generate_horizon.py using python-chess."]
    start = chess.Board("7k/8/8/8/8/8/8/KR6 w - - 0 1")
    cycle = [chess.Move.from_uci(m) for m in ("b1b2", "h8h7", "b2b1", "h7h8")]
    for mirror in (False, True):
        board = start.mirror() if mirror else start.copy()
        initial = board.fen()
        moves = [chess.Move(m.from_square ^ 56, m.to_square ^ 56) for m in cycle] if mirror else cycle
        sequence = []
        for occurrence in (1, 2):
            for move in moves:
                assert move in board.legal_moves
                sequence.append(move.uci())
                board.push(move)
            assert board.is_repetition(3) == (occurrence == 2)
            history_lines.append('{"%s", "%s", "%s", %s},' % (
                initial, board.fen(), " ".join(sequence), str(board.is_repetition(3)).lower()))
            for mode in (-1, 0, 1):
                visit(board, mode, 0)
    lines = ["// Generated by generate_horizon.py using python-chess."]
    for fen, (check, terminal, legal, entry, negative) in sorted(nodes.items()):
        lines.append('{"%s", %s, %d, "%s", "%s", "%s"},' % (
            fen, str(check).lower(), terminal, legal, entry, negative))
    root_lines = ['// Generated by generate_horizon.py using python-chess.']
    root_lines += ['"%s",' % fen for fen in roots]
    return tuple("\n".join(rows) + "\n" for rows in (lines, root_lines, history_lines))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, data in zip(("horizon.inc", "horizon_roots.inc", "horizon_history.inc"), generate()):
        path = Path(__file__).with_name(name)
        if args.check:
            if path.read_text() != data:
                raise SystemExit(name + " certificates differ")
        else:
            path.write_text(data)
